"""Reproduce this chapter's independent platform-entry checks.

Requires Python 3.10+ and an existing GCC/Clang-compatible C++17 compiler. Select
the compiler with --compiler, CXX, or the default executable name c++.
Everything generated by this script stays in the repository's .local folder.
This is a standalone evidence tool; it does not register or change CI targets.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import os
from pathlib import Path
import random
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / ".local" / "boundary-platform-entries"
DEFAULT_SOURCE = Path("content/boundary-feasibility/边界与答案.cpp")
TEST = ROOT / "tests/cpp/boundary_feasibility_test.cpp"
SEED = 0xA10851620


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def compiler_executable(value: str) -> str:
    """CXX names one executable, rather than a shell command or flags."""
    expanded = os.path.expandvars(os.path.expanduser(value))
    candidate = Path(expanded)
    if candidate.is_file():
        return str(candidate.resolve())
    found = shutil.which(expanded)
    if found:
        return found
    raise ValueError(f"C++ compiler executable not found: {value!r}")


def factory_by_countdown(periods: list[int], target: int) -> int:
    """Independently advance every machine by one second, without division."""
    countdowns = periods[:]
    produced = 0
    second = 0
    while produced < target:
        second += 1
        for index, period in enumerate(periods):
            countdowns[index] -= 1
            if countdowns[index] == 0:
                produced += 1
                countdowns[index] = period
    return second


def division_by_combinations(values: list[int], groups: int) -> int:
    """Enumerate exactly groups-1 cuts, keeping every subarray nonempty."""
    best = sum(values)
    for cuts in itertools.combinations(range(1, len(values)), groups - 1):
        endpoints = (0,) + cuts + (len(values),)
        score = max(sum(values[a:b]) for a, b in zip(endpoints, endpoints[1:]))
        best = min(best, score)
    return best


class PlatformChecks:
    def __init__(self, source: Path, compiler: str) -> None:
        self.source = source
        self.compiler = compiler
        self.env = dict(os.environ, TEMP=str(OUTPUT), TMP=str(OUTPUT),
                        TMPDIR=str(OUTPUT), PYTHONDONTWRITEBYTECODE="1")
        self.builds: list[dict] = []
        self.checks: list[dict] = []

    def build(self, name: str, source: Path, define: str | None = None) -> Path:
        suffix = ".exe" if os.name == "nt" else ""
        executable = OUTPUT / f"{name}{suffix}"
        command = [self.compiler, "-std=c++17", "-O2", "-Wall", "-Wextra",
                   "-Wpedantic", "-finput-charset=UTF-8"]
        if define:
            command.append(f"-D{define}")
        command += [str(source), "-o", str(executable)]
        process = subprocess.run(command, cwd=OUTPUT, env=self.env,
                                 capture_output=True, timeout=60)
        log = process.stdout + process.stderr
        log_path = OUTPUT / f"{name}-build.log"
        log_path.write_bytes(log)
        self.builds.append({"name": name, "command": command,
                            "returncode": process.returncode,
                            "diagnostic_bytes": len(log)})
        if process.returncode:
            raise RuntimeError(f"{name} build failed; inspect {log_path.name}")
        return executable

    def run_case(self, executable: Path, label: str, data: str, expected: int) -> None:
        process = subprocess.run([str(executable)], input=data.encode("ascii"),
                                 cwd=OUTPUT, env=self.env, capture_output=True, timeout=15)
        actual = process.stdout.decode("ascii").split()
        result = {"name": label, "input_bytes": len(data), "expected": expected,
                  "returncode": process.returncode,
                  "stdout": process.stdout.decode("ascii"),
                  "stderr": process.stderr.decode(errors="replace")}
        self.checks.append(result)
        if process.returncode or process.stderr or actual != [str(expected)]:
            (OUTPUT / "failure-input.txt").write_text(data, encoding="ascii")
            raise AssertionError(f"{label} failed; inspect results.json and failure-input.txt")

    def check_acm_entries(self) -> None:
        rng = random.Random(SEED)
        factory = self.build("factory-main", self.source, "SECOND_ALGORITHM_FACTORY_MAIN")
        division = self.build("division-main", self.source, "SECOND_ALGORITHM_DIVISION_MAIN")
        self.run_case(factory, "factory official example", "3 7\n3 2 5\n", 8)
        self.run_case(factory, "factory one slow machine 10^18",
                      "1 1000000000\n1000000000\n", 10**18)
        self.run_case(factory, "factory all machines simultaneous", "2 5\r\n2 3\r\n", 6)
        self.run_case(division, "division official example", "5 3\n2 4 7 3 5\n", 8)
        self.run_case(division, "division exact k refinement", "4 3\r\n1 1 1 1\r\n", 2)
        self.run_case(division, "division singleton", "1 1\n1000000000\n", 10**9)
        for trial in range(40):
            periods = [rng.randint(1, 10) for _ in range(rng.randint(1, 6))]
            target = rng.randint(1, 20)
            data = f"{len(periods)} {target}\n" + " ".join(map(str, periods)) + "\n"
            self.run_case(factory, f"factory countdown random {trial}", data,
                          factory_by_countdown(periods, target))
        for trial in range(40):
            values = [rng.randint(1, 20) for _ in range(rng.randint(1, 8))]
            groups = rng.randint(1, len(values))
            data = f"{len(values)} {groups}\n" + "\n".join(map(str, values)) + "\n"
            self.run_case(division, f"division cuts random {trial}", data,
                          division_by_combinations(values, groups))
        large_line = " ".join(["1000000000"] * 200000) + "\n"
        for groups, expected in [(1, 200000000000000), (3, 66667000000000),
                                 (200000, 1000000000)]:
            self.run_case(division, f"division full size k={groups}",
                          f"200000 {groups}\n" + large_line, expected)
        self.run_case(factory, "factory full size 200000 machines",
                      "200000 1000000000\n" + " ".join(["1"] * 200000) + "\n", 5000)

    def check_lc_entries(self) -> None:
        include = self.source.as_posix()
        lc34_runner = OUTPUT / "lc34-runner.cpp"
        lc34_runner.write_text('''#define SECOND_ALGORITHM_LC34
#include "''' + include + '''"
int main() {
    Solution solver;
    std::vector<int> a{5,7,7,8,8,10};
    std::vector<int> b;
    std::vector<int> c(100000,7);
    if (solver.searchRange(a,8) != std::vector<int>{3,4}) return 1;
    if (solver.searchRange(a,6) != std::vector<int>{-1,-1}) return 2;
    if (solver.searchRange(b,0) != std::vector<int>{-1,-1}) return 3;
    if (solver.searchRange(c,7) != std::vector<int>{0,99999}) return 4;
    std::cout << "4\\n";
}
''', encoding="utf-8")
        lc875_runner = OUTPUT / "lc875-runner.cpp"
        lc875_runner.write_text('''#define SECOND_ALGORITHM_LC875
#include "''' + include + '''"
int main() {
    Solution solver;
    std::vector<int> a{3,6,7,11};
    std::vector<int> b{30,11,23,4,20};
    std::vector<int> c(10000,1000000000);
    if (solver.minEatingSpeed(a,8) != 4) return 1;
    if (solver.minEatingSpeed(b,5) != 30) return 2;
    if (solver.minEatingSpeed(b,6) != 23) return 3;
    if (solver.minEatingSpeed(c,1000000000) != 10000) return 4;
    std::cout << "4\\n";
}
''', encoding="utf-8")
        for name, source in [("lc34-adapter", lc34_runner), ("lc875-adapter", lc875_runner)]:
            self.run_case(self.build(name, source), name, "", 4)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", help="One GCC/Clang-compatible executable; defaults to CXX or c++")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE,
                        help="Same-API source; relative paths start at the repository root")
    arguments = parser.parse_args()
    try:
        compiler = compiler_executable(arguments.compiler or os.environ.get("CXX") or "c++")
    except ValueError as error:
        parser.error(str(error))
    source = arguments.source
    if not source.is_absolute():
        source = ROOT / source
    source = source.resolve()
    if not source.is_file():
        parser.error(f"Source file not found: {arguments.source}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    initial_hash = digest(source)
    verifier = PlatformChecks(source, compiler)
    result = {"source_sha256": initial_hash, "test_sha256": digest(TEST),
              "tool_sha256": digest(Path(__file__)), "seed": hex(SEED),
              "builds": verifier.builds, "checks": verifier.checks, "status": "running"}
    result_path = OUTPUT / "results.json"
    result_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    try:
        verifier.check_acm_entries()
        verifier.check_lc_entries()
        if digest(source) != initial_hash:
            raise RuntimeError("Source changed during platform verification; rerun on stable inputs")
        adapters = [item for item in verifier.checks if item["name"].endswith("-adapter")]
        acm_checks = len(verifier.checks) - len(adapters)
        adapter_assertions = sum(int(item["stdout"].strip()) for item in adapters)
        if (acm_checks, len(adapters), adapter_assertions) != (90, 2, 8):
            raise AssertionError("Expected platform check groups were not all executed")
        result.update(acm_checks=acm_checks, lc_adapters=len(adapters),
                      lc_adapter_assertions=adapter_assertions, status="passed")
    except Exception as error:
        result.update(status="failed", error=str(error))
        result_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    result_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    summary = {key: result[key] for key in ["source_sha256", "tool_sha256", "seed", "acm_checks",
                                          "lc_adapters", "lc_adapter_assertions", "status"]}
    summary["results"] = result_path.relative_to(ROOT).as_posix()
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
